import AppKit
import SwiftUI

/// Recent copied texts, newest first. Kept in memory only: copied text can be a secret, so it is
/// never written to disk.
struct ClipboardHistory: Equatable {
    struct Item: Equatable, Identifiable {
        var text: String
        var copiedAt: Date
        var id: String { text }
    }

    var items: [Item] = []
    var limit = 50

    /// A repeat copy moves the existing entry to the top instead of adding a duplicate.
    mutating func add(_ text: String, at date: Date = Date()) {
        guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }
        items.removeAll { $0.text == text }
        items.insert(Item(text: text, copiedAt: date), at: 0)
        if items.count > limit { items.removeLast(items.count - limit) }
    }

    func matching(_ query: String) -> [Item] {
        let q = query.trimmingCharacters(in: .whitespaces)
        return q.isEmpty ? items : items.filter { $0.text.localizedCaseInsensitiveContains(q) }
    }

    /// Password managers mark their copies with these types (nspasteboard.org); they are skipped.
    static let privateTypes: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                                            "org.nspasteboard.AutoGeneratedType"]

    static func shouldRecord(types: [String]) -> Bool {
        types.contains(NSPasteboard.PasteboardType.string.rawValue) && privateTypes.isDisjoint(with: types)
    }
}

@MainActor
final class ClipboardModel: ObservableObject {
    @Published private(set) var history = ClipboardHistory()
    @Published var isShown = false
    private var lastChange = NSPasteboard.general.changeCount
    private var timer: Timer?

    /// NSPasteboard has no change notification; polling `changeCount` is the standard way and costs
    /// one integer read per tick.
    func start() {
        guard timer == nil else { return }
        timer = Timer.scheduledTimer(withTimeInterval: 0.75, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        let types = (pb.types ?? []).map(\.rawValue)
        guard ClipboardHistory.shouldRecord(types: types), let text = pb.string(forType: .string) else { return }
        history.add(text)
    }

    func copy(_ item: ClipboardHistory.Item) {
        NSPasteboard.general.clearContents()
        NSPasteboard.general.setString(item.text, forType: .string)
        history.add(item.text)
        lastChange = NSPasteboard.general.changeCount
    }

    func clear() { history.items.removeAll() }
}

/// Toolbar button with a searchable list of recent copies; clicking an entry copies it again.
struct ClipboardButton: View {
    @ObservedObject var clipboard: ClipboardModel

    var body: some View {
        Button { clipboard.isShown.toggle() } label: {
            ToolbarKeyLabel(title: "Clipboard History", icon: "list.clipboard", key: Shortcuts.clipboard)
        }
        .help(Shortcuts.hint("Clipboard history", Shortcuts.clipboard))
        .popover(isPresented: $clipboard.isShown, arrowEdge: .bottom) {
            ClipboardList(clipboard: clipboard) { clipboard.isShown = false }
        }
    }
}

/// Keyboard first, like Maccy: type to filter, Up/Down to select, Return copies the selection,
/// Cmd-1 to Cmd-9 copy that row directly, Escape closes.
struct ClipboardList: View {
    @ObservedObject var clipboard: ClipboardModel
    let done: () -> Void
    @State private var query = ""
    @State private var selected = 0
    @FocusState private var searchFocused: Bool

    var body: some View {
        let items = clipboard.history.matching(query)
        VStack(spacing: 0) {
            TextField("Search", text: $query)
                .textFieldStyle(.plain)
                .font(.body)
                .focused($searchFocused)
                .padding(.horizontal, 12).padding(.vertical, 10)
                .onSubmit { if items.indices.contains(selected) { pick(items[selected]) } }
                .onKeyPress(.downArrow) { move(1, count: items.count) }
                .onKeyPress(.upArrow) { move(-1, count: items.count) }
                .onKeyPress(.escape) { done(); return .handled }
                .onKeyPress(characters: .decimalDigits, phases: .down) { press in
                    guard press.modifiers == .command, let n = Int(press.characters), n >= 1,
                          items.indices.contains(n - 1) else { return .ignored }
                    pick(items[n - 1])
                    return .handled
                }
                .onChange(of: query) { _, _ in selected = 0 }
            Divider()
            if items.isEmpty {
                Text(clipboard.history.items.isEmpty ? "Nothing copied since launch." : "No matches.")
                    .foregroundStyle(.secondary).frame(maxWidth: .infinity, minHeight: 80)
            } else {
                ScrollViewReader { proxy in
                    ScrollView {
                        LazyVStack(spacing: 0) {
                            ForEach(Array(items.enumerated()), id: \.element.id) { n, item in
                                row(item, index: n).id(n)
                            }
                        }
                        .padding(4)
                    }
                    .frame(maxHeight: 420)
                    .onChange(of: selected) { _, n in proxy.scrollTo(n) }
                }
            }
            Divider()
            HStack {
                Text("\u{2191}\u{2193} select   \u{21A9} copy   \(Shortcuts.cmd)1-9 copy row")
                Spacer()
                Button("Clear") { clipboard.clear() }.buttonStyle(.borderless)
                    .disabled(clipboard.history.items.isEmpty)
            }
            .font(.caption).foregroundStyle(.secondary)
            .padding(.horizontal, 12).padding(.vertical, 6)
        }
        .frame(width: 400)
        .onAppear { searchFocused = true; selected = 0 }
    }

    private func move(_ by: Int, count: Int) -> KeyPress.Result {
        guard count > 0 else { return .handled }
        selected = min(count - 1, max(0, selected + by))
        return .handled
    }

    private func row(_ item: ClipboardHistory.Item, index: Int) -> some View {
        let isSelected = index == selected
        return HStack(alignment: .firstTextBaseline, spacing: 8) {
            Text(index < 9 ? "\(index + 1)" : "").font(.caption.monospacedDigit()).foregroundStyle(.tertiary)
                .frame(width: 10, alignment: .trailing)
            Text(item.text.trimmingCharacters(in: .whitespacesAndNewlines))
                .lineLimit(2).truncationMode(.tail)
                .frame(maxWidth: .infinity, alignment: .leading)
            Text(item.copiedAt, style: .relative).font(.caption.monospacedDigit()).foregroundStyle(.tertiary)
        }
        .font(.callout)
        .padding(.horizontal, 8).padding(.vertical, 6)
        .background(RoundedRectangle(cornerRadius: 5).fill(isSelected ? Palette.accent.opacity(0.22) : .clear))
        .contentShape(Rectangle())
        .onHover { if $0 { selected = index } }
        .onTapGesture { pick(item) }
        .help(String(item.text.prefix(1000)))
    }

    private func pick(_ item: ClipboardHistory.Item) {
        clipboard.copy(item)
        done()
    }
}
